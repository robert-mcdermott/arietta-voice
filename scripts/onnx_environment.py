ENV_KEYS = ('ONNX_PROVIDER', 'OMP_NUM_THREADS', 'MKL_NUM_THREADS', 'OPENBLAS_NUM_THREADS',
            'VECLIB_MAXIMUM_THREADS', 'TOKENIZERS_PARALLELISM')


def snapshot():
    """Record public dependency versions/code, never tokens or arbitrary environment."""
    packages = {d.metadata['Name'].lower().replace('_', '-'): d.version for d in distributions()}
    files = {}
    for package in ('kokoro-onnx', 'onnxruntime', 'numpy', 'phonemizer-fork', 'espeakng-loader'):
        dist = distribution(package)
        selected = {}
        for name in dist.files or ():
            # Includes native libraries, excludes generated bytecode/installation paths.
            if str(name).endswith(('.py', '.so', '.dylib')):
                with dist.locate_file(name).open('rb') as handle:
                    selected[str(name)] = hashlib.file_digest(handle, 'sha256').hexdigest()
        files[package] = selected
    return dict(packages=packages, implementation_sha256=files,
                environment={k: os.environ.get(k) for k in ENV_KEYS})


class StageTimer:
    def __init__(self):
        self.reset()

    def reset(self):
        self.wall, self.cpu, self.calls = defaultdict(float), defaultdict(float), defaultdict(int)
        self.phonemes = []

    def wrap(self, name, function):
        def timed(*args, **kwargs):
            start, cpu = time.perf_counter(), time.process_time()
            try:
                result = function(*args, **kwargs)
            finally:
                self.wall[name] += (time.perf_counter()-start)*1000
                self.cpu[name] += (time.process_time()-cpu)*1000
                self.calls[name] += 1
            if name == 'phonemize':
                self.phonemes.append(hashlib.sha256(result.encode()).hexdigest())
            return result
        return timed


class SessionProxy:
    def __init__(self, session, timer):
        self.session = session
        self.run = timer.wrap('onnx_run', session.run)

    def __getattr__(self, name):
        return getattr(self.session, name)


def probe(args):
    import asyncio
    from arietta_voice.assets import cache_root
    from arietta_voice.tts import KokoroTextToSpeech
    from scripts.hardware_validation import isolated_config, validation_lock
    os.environ.update(HF_HUB_OFFLINE='1', TRANSFORMERS_OFFLINE='1', HF_HUB_DISABLE_IMPLICIT_TOKEN='1')
    with validation_lock(ROOT/'tmp/hardware-validation'):
        for name in ('kokoro-v1.0.onnx', 'voices-v1.0.bin'):
            if not (cache_root()/'kokoro'/name).is_file():
                raise ValueError('Cached ONNX assets are required; no downloads in this probe')
        engine = None
        if args.resident:
            from arietta_voice.config import load_config
            from arietta_voice.inference import InferenceEngine
            config = isolated_config(load_config(args.config), args.output.with_suffix('')/'profile')
            config.audio.tts_backend = 'onnx'
            config.audio.voice, config.audio.tts_speed = 'af_heart', 1.
            config.audio.tts_enabled = config.audio.smart_turn_enabled = True
            engine = InferenceEngine(config)
            engine.handle('warmup', None)
            # Exercise Gemma once before TTS; don't measure its initial compilation.
            engine.handle('chat', dict(message='What is two plus two?', history=(), use_tools=False,
                enabled_tools=(), enabled_model_tools=(), max_tokens=64))
            speaker = engine.speaker()
        else:
            speaker = KokoroTextToSpeech('af_heart', 1.)
            speaker.ensure_loaded()
        import kokoro_onnx
        kokoro, timer = speaker._kokoro, StageTimer()
        session, phonemize, trim = kokoro.sess, kokoro.tokenizer.phonemize, kokoro_onnx.trim_audio
        options = session.get_session_options()
        report = dict(status='running', environment_label=args.label, resident=args.resident,
            repeats=args.repeats, cases=[], providers=session.get_providers(),
            intra_op_threads=options.intra_op_num_threads, inter_op_threads=options.inter_op_num_threads,
            execution_mode=str(options.execution_mode), optimization=str(options.graph_optimization_level),
            corpus_sha256=hashlib.sha256(json.dumps(CASES[:3]).encode()).hexdigest(),
            harness_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest())
        kokoro.sess = SessionProxy(session, timer)
        kokoro.tokenizer.phonemize = timer.wrap('phonemize', phonemize)
        kokoro_onnx.trim_audio = timer.wrap('trim', trim)
        async def generate():
            _, report['initial'] = await measure(speaker.create_stream(FIRST_TEXT))
            for repeat in range(args.repeats):
                for name, text in CASES[:3]:
                    timer.reset()
                    pcm, row = await measure(speaker.create_stream(text))
                    if row['silent'] or row['clipped_fraction']:
                        raise ValueError('Invalid probe signal')
                    row.update(id=name, repeat=repeat, pcm_sha256=hashlib.sha256(pcm.tobytes()).hexdigest(),
                        stage_wall_ms=dict(timer.wall), stage_cpu_ms=dict(timer.cpu),
                        stage_calls=dict(timer.calls), phoneme_sha256=timer.phonemes.copy())
                    report['cases'].append(row)
                    write_json(args.output, report)
        try:
            asyncio.run(generate())
            report['loaded_modules'] = {k: k in sys.modules for k in ('scipy','spacy','mlx_audio','torch','transformers')}
            if engine:
                report['resources'] = engine.handle('resource_snapshot', None)
                import torch
                report['torch_threads'] = torch.get_num_threads()
            report['snapshot'] = snapshot()  # Hashing is outside all measurements.
            report['status'] = 'passed'
        finally:
            kokoro.sess, kokoro.tokenizer.phonemize, kokoro_onnx.trim_audio = session, phonemize, trim
            if engine:
                engine.handle('speech_close', None)
                engine._loop.close()
            write_json(args.output, report)


def compare_blocks(blocks):
    """Compare balanced ONNX conversation blocks while preserving block variability."""
    if not blocks:
        raise ValueError('No blocks')
    labels = {b['environment'] for b in blocks}
    if labels != {'production', 'trial'}:
        raise ValueError('Production and trial blocks are required')
    if sum(b['environment']=='production' for b in blocks) != sum(b['environment']=='trial' for b in blocks):
        raise ValueError('Unbalanced environments')
    first = blocks[0]['report']
    metadata = blocks[0]['metadata']
    metadata_keys = ('models', 'audio', 'chime_enabled', 'temperature', 'seed',
                     'cached_revisions', 'asset_sha256', 'stt_asset_sha256', 'benchmark_sha256')
    identities = lambda r: [(x['case_id'], x['first_turn'], x['history_turns']) for x in r['rows']]
    for block in blocks:
        r = block['report']
        if (r['status'] != 'passed' or not r['gates'] or not all(r['gates'].values()) or
                r['tts_backend'] != 'onnx' or len(r['rows']) != r['requested_warm_turns']+1 or
                not r['rows'][0]['first_turn'] or sum(x['first_turn'] for x in r['rows']) != 1 or
                not all(x['valid'] and x.get('response_sha256') for x in r['rows'])):
            raise ValueError('Failed or incomplete ONNX block')
        if any(block['metadata'][k] != metadata[k] for k in metadata_keys):
            raise ValueError('Mismatched model/audio/benchmark metadata')
        if any(r[k] != first[k] for k in ('fixture_sha256','conversation_turns','requested_warm_turns')) or identities(r) != identities(first):
            raise ValueError('Mismatched protocol')
        if [x['response_sha256'] for x in r['rows']] != [x['response_sha256'] for x in first['rows']]:
            raise ValueError('Mismatched responses; do not attribute different work to the environment')
    result = {}
    for label in sorted(labels):
        selected = [b['report'] for b in blocks if b['environment']==label]
        rows = [r for block in selected for r in block['rows']]
        result[label] = dict(blocks=len(selected), **summarize_turns(rows),
            block_first_write_p50_ms=[summarize_turns(b['rows'])['metrics_ms']['speech_end_to_first_write_ms']['p50'] for b in selected])
    # Paired by case/history within corresponding blocks, not a confidence interval.
    groups = [[b['report']['rows'][1:] for b in blocks if b['environment']==label] for label in ('production','trial')]
    differences = [t['speech_end_to_first_write_ms']-p['speech_end_to_first_write_ms']
                   for pb,tb in zip(*groups) for p,t in zip(pb,tb)]
    result['paired_trial_minus_production_ms'] = quantiles(differences)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='command', required=True)
    p = sub.add_parser('probe')
    p.add_argument('--label', choices=['production','trial'], required=True)
    p.add_argument('--resident', action='store_true')
    p.add_argument('--config', type=Path)
    p.add_argument('--repeats', type=int, default=5)
    p.add_argument('--output', type=Path, required=True)
    p = sub.add_parser('compare')
    p.add_argument('manifest', type=Path, help='JSON list with environment and report directory per block')
    p.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    os.umask(0o077)
    if args.output.exists() or not args.output.resolve().is_relative_to(ROOT/'tmp'):
        parser.error('Use a fresh output file under repository tmp')
    if args.command == 'probe':
        if not 1 <= args.repeats <= 10:
            parser.error('repeats must be 1..10')
        args.timeout = 240
        run_bounded(args, target=probe)
    else:
        blocks = [dict(environment=b['environment'], report=json.loads((Path(b['directory'])/'report.json').read_text()),
                       metadata=json.loads((Path(b['directory'])/'environment.json').read_text()))
                  for b in json.loads(args.manifest.read_text())]
        write_json(args.output, compare_blocks(blocks))


if __name__ == '__main__':
    main()
